"""
mappings.py — PPC ↔ ARM instruction mapping table.

Exports
-------
MappingEntry   dataclass describing a single mapping
PPC_TO_ARM     dict[str, MappingEntry]  — keyed by lowercase PPC mnemonic
ARM_TO_PPC     dict[str, MappingEntry]  — keyed by uppercase ARM mnemonic
               (built automatically by inverting PPC_TO_ARM)

Confidence levels
-----------------
"direct"     — near-identical semantics; safe 1-to-1 substitution
"close"      — same intent, minor semantic/register-model differences
"suggestion" — closest approximation; programmer must verify
"none"       — no reasonable analogue; noted for completeness

Key architectural differences to keep in mind
----------------------------------------------
- PPC is big-endian by default; ARM/AArch64 is little-endian by default.
- PPC has 32 GPRs (r0–r31); ARM/AArch64 has 31 GPRs (X0–X30) plus XZR/SP.
- PPC has a Condition Register (CR) with 8 fields; ARM uses NZCV flags.
- PPC update-form instructions (lwzu, stwu …) auto-increment the base register;
  ARM post/pre-indexed forms (LDR Xt,[Xn],#simm) cover the same idiom.
- PPC AltiVec/VMX is big-endian 128-bit SIMD;
  ARM NEON/ASIMD is little-endian 128-bit SIMD.
- PPC64 has 64-bit registers throughout; AArch64 has both Wn (32-bit) and
  Xn (64-bit) views of the same registers.
"""

