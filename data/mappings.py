# ---------------------------------------------------------------------------
# Reverse table: ARM → PPC
# (auto-built by inverting PPC_TO_ARM; entries with multiple PPC sources
#  are represented by the first encountered mapping)
# ---------------------------------------------------------------------------

def _build_reverse(forward: dict[str, MappingEntry]) -> dict[str, MappingEntry]:
    reverse: dict[str, MappingEntry] = {}
    for ppc_mnem, entry in forward.items():
        for arm_target in entry.targets:
            if arm_target not in reverse:
                reverse[arm_target] = MappingEntry(
                    source=arm_target,
                    targets=[ppc_mnem],
                    confidence=entry.confidence,
                    notes=entry.notes,
                    mode=entry.mode,
                )
            else:
                # Append additional PPC sources
                if ppc_mnem not in reverse[arm_target].targets:
                    reverse[arm_target].targets.append(ppc_mnem)
    return reverse


ARM_TO_PPC: dict[str, MappingEntry] = _build_reverse(PPC_TO_ARM)
